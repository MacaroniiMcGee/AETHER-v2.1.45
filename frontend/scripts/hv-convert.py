"""
hv-convert.py — move Aether frontend colors onto the HV GUI Guidelines (v3.435) tokens.

Run from frontend/:   python3 scripts/hv-convert.py src            (dry run, prints a summary)
                      python3 scripts/hv-convert.py src --apply    (rewrite files)

What it does, per .ts/.tsx file (safe to re-run; already-converted code is left alone):
  1. Every color literal (#hex, rgba(), Tailwind arbitrary value) -> HV semantic token
       bg-[#241E19]/40  -> bg-hv-widget/40        '#F0A73C' -> 'rgb(var(--hv-brand))'
     Legacy Aether colors are first mapped to their HV Dark equivalent (LEGACY table),
     then snapped to the nearest token in the same HV family. Status colors used as
     text become *-fg so they stay readable in Light mode.
  2. text-white -> text-hv-text, except on solid accent buttons (white stays white).
  3. Translucent black wells (bg-black/NN, rgba(0,0,0,a) backgrounds) -> surface token;
     modal backdrops (fixed inset-0) keep HV Dim black.
  4. String-built alpha colors (color + '30', ${c}26) -> color-mix(), so tokens work.
  5. Known categorical maps get one HV Data color per category.
Tokens live in src/theme/hv-tokens.css (generated by scripts/hv-tokens.py).
"""
