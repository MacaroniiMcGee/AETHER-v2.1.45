SOLID = {'brand', 'brand-hover', 'success-strong', 'success-hover', 'success', 'error-strong',
         'error-hover', 'error', 'info-strong', 'info', 'purple', 'violet', 'pink'}

def family(h):
    r, g, b = rgb(h); hue, l, s = colorsys.rgb_to_hls(r, g, b); d = hue*360
    if s < 0.15 or l < 0.05 or l > 0.97: return 'neutral'
    return ('error' if d < 12 or d >= 345 else 'brand' if d < 40 else 'warning' if d < 62 else
            'success' if d < 175 else 'info' if d < 255 else 'purple' if d < 285 else 'violet' if d < 300 else 'pink')

def snap(h):
    if h == '000000': return None
    h = legacy_to_hv(h)
    if h in EXACT: return EXACT[h]
    if h == 'FFFFFF': return 'text'
    return min(FAMILY_TOKENS[family(h)], key=lambda t: abs(lum(TOKENS[t][0]) - lum(h)))

def finalize(tok, text_ctx, raw, solid_line):
    if tok is None: return None
    if legacy_to_hv(raw) == 'FFFFFF' and solid_line: return 'WHITE'   # white label on a solid accent stays white
    if text_ctx and lum(raw) < 0.10: return 'INK'   # near-black text on a colored badge stays dark in both themes
    if text_ctx and tok in FG: return FG[tok]
    if text_ctx and tok == 'line-strong': return 'text-disabled'
    return tok

TW = re.compile(r'(?P<pre>[a-z:\-]*?(?:bg|text|border(?:-[trblxy])?|ring|ring-offset|from|to|via|fill|stroke|divide|outline|placeholder|shadow|accent|caret|decoration))-\[(?P<val>#[0-9A-Fa-f]{3,8}|rgba?\(\s*\d[^\]]*\))\](?P<alpha>/\d+)?')
HEX = re.compile(r'(?<!-\[)#([0-9A-Fa-f]{8}|[0-9A-Fa-f]{6}|[0-9A-Fa-f]{3})(?![0-9A-Za-z_-])')   # skips values already inside a Tailwind -[...] class, and ids like url(#cab-wall)
RGBA = re.compile(r'rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)')
PROP = re.compile(r'(\b[A-Za-z]+)\s*[:=]\s*\{?\s*[\'"`]?[^\'"`,;{}]*$')
stats = {}

def solid_on(line):
    if SOLID_CLS.search(line): return True      # already-tokenized solid accent background
    for m in HEX.finditer(line):
        if len(m.group(1)) == 8: continue
        pre = line[max(0, m.start()-30):m.start()]
        if line[m.end():m.end()+2] == ']/': continue          # translucent tint, not a solid fill
        if re.search(r'(bg-\[|background(Color)?\s*:\s*[\'"`]?)$', pre) and snap(norm(m.group(1))) in SOLID: return True
    for m in RGBA.finditer(line):
        pre = line[max(0, m.start()-30):m.start()]
        h = '%02X%02X%02X' % tuple(int(x) for x in m.groups()[:3])
        if not m.group(4) and re.search(r'background(Color)?\s*:\s*[\'"`]?$', pre) and snap(h) in SOLID: return True
    return False

def convert_line(line):
    if '#' not in line and 'rgb' not in line: return line
    solid = solid_on(line)
    def tw(m):
        pre, val, alpha = m.group('pre'), m.group('val'), m.group('alpha') or ''
        tctx = re.search(r'(?:^|-)(text|placeholder|caret|decoration)$', pre) is not None
        if val.startswith('#'):
            h = norm(val[1:7] if len(val) > 4 else val[1:]); a = int(val[7:9], 16)/255 if len(val) == 9 else None
        else:
            n = re.findall(r'[\d.]+', val); h = ''.join(f'{int(x):02X}' for x in n[:3]); a = float(n[3]) if len(n) > 3 else None
        tok = finalize(snap(h), tctx, h, solid); stats[tok or 'kept'] = stats.get(tok or 'kept', 0) + 1
        if tok == 'WHITE': return f'{pre}-[#FFFFFF]{alpha}'
        if tok == 'INK': return f'{pre}-[#101011]{alpha}'
        if not tok: return m.group(0)
        if a is not None and not alpha: alpha = f'/[{round(a, 2)}]'
        return f'{pre}-hv-{tok}{alpha}'
    line = TW.sub(tw, line)
    def ctx(i):
        m = PROP.search(line[:i]); p = m.group(1) if m else ''
        return p == 'color' or p.endswith('TextColor')
    def hx(m):
        v = m.group(1); h = norm(v[:6] if len(v) == 8 else v)
        tok = finalize(snap(h), ctx(m.start()), h, solid); stats[tok or 'kept'] = stats.get(tok or 'kept', 0) + 1
        if tok == 'WHITE': return '#FFFFFF' + (v[6:8] if len(v) == 8 else '')
        if tok == 'INK': return '#101011' + (v[6:8] if len(v) == 8 else '')
        if not tok: return m.group(0)
        if len(v) == 8: return f'rgb(var(--hv-{tok}) / {round(int(v[6:8], 16)/255, 2)})'
        return f'rgb(var(--hv-{tok}))'
    line = HEX.sub(hx, line)
    def rg(m):
        r, g, b, a = m.groups(); h = f'{int(r):02X}{int(g):02X}{int(b):02X}'
        if h == '000000': return m.group(0)
        if h == 'FFFFFF': tok = 'contrast'
        else: tok = finalize(snap(h), ctx(m.start()), h, False)
        if tok in ('WHITE', 'INK'): tok = None
        stats[tok or 'kept'] = stats.get(tok or 'kept', 0) + 1
        if not tok: return m.group(0)
        return f'rgb(var(--hv-{tok}) / {a})' if a else f'rgb(var(--hv-{tok}))'
    return RGBA.sub(lambda m: m.group(0) if 'var(--hv-' in m.group(0) else rg(m), line)

# ── 2-4. Line passes ─────────────────────────────────────────────────────────
SOLID_CLS = re.compile(r"bg-hv-(brand|brand-hover|success|success-strong|success-hover|error|error-strong|error-hover|info|info-strong|purple|violet|pink|data-[a-z]+)(?![\w-])(?!/)|bg-(red|rose|emerald|green|blue|sky|orange|cyan|teal|purple|violet|indigo|pink|amber|yellow)-(500|600|700)(?!/)|background(Color)?:\s*'rgb\(var\(--hv-(brand|success-strong|success|error-strong|error|info-strong|info|purple)\)\)'")
def pct(h): return f'{round(int(h, 16)/255*100)}%'

def convert_text(t):
    out = []
    for l in t.split('\n'):
        l = convert_line(l)
        if 'white' in l:
            l = re.sub(r'\b((?:[a-z]+:)*)bg-white/(\d+)', r'\1bg-hv-contrast/\2', l)
            if re.search(r'\btext-white\b', l) and not SOLID_CLS.search(' '.join(out[-2:] + [l])):
                l = re.sub(r'\btext-white\b', 'text-hv-text', l)
        if 'fixed inset-0' not in l:   # modal backdrops keep HV Dim black
            l = re.sub(r'(?<![\w-])((?:[a-z]+:)*)bg-black/(\d+)', r'\1bg-hv-surface/\2', l)
        if 'fixed inset-0' not in l and 'shadow' not in l.lower():
            l = re.sub(r"((?:background|backgroundColor)\s*:\s*')rgba\(\s*0\s*,\s*0\s*,\s*0\s*,\s*([\d.]+)\s*\)'", r"\1rgb(var(--hv-surface) / \2)'", l)
        l = re.sub(r"([A-Za-z_][\w.\[\]]*)\s*\+\s*'([0-9A-Fa-f]{2})'", lambda m: f"`color-mix(in srgb, ${{{m.group(1)}}} {pct(m.group(2))}, transparent)`", l)
        l = re.sub(r"\$\{([^{}]+)\}([0-9A-Fa-f]{2})(?=[\s,`)])", lambda m: f"color-mix(in srgb, ${{{m.group(1)}}} {pct(m.group(2))}, transparent)", l)
        out.append(l)
    return '\n'.join(out)

