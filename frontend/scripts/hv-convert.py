def apply_data_maps(path, t):
    for rel, pat, val, mapping in DATA_MAPS:
        if str(path).replace('\\', '/').endswith(rel):
            for k, tok in mapping.items():
                t = re.sub(pat % re.escape(k), lambda m: m.group(1) + val(tok) + m.group(2), t, count=1)
    return t

# Drawings of physical things keep their real colors in both themes; after a conversion run,
# restore them with scripts/hv-artwork.py (needs the pre-HV commit it names in BASE).
ARTWORK = ('DoorAnimation.tsx', 'InteractiveReader.tsx', 'InteractiveWiegandReader.tsx', 'ElevatorSection.tsx', 'SwitchSection.tsx')

def main():
    src = pathlib.Path(sys.argv[1]); apply = '--apply' in sys.argv
    changed = []
    for p in sorted(src.rglob('*')):
        if p.suffix not in ('.ts', '.tsx') or not p.is_file() or 'theme' in p.parts: continue
        t = p.read_text(encoding='utf-8')
        nt = apply_data_maps(p, convert_text(t))
        if nt != t:
            changed.append(str(p))
            if apply: p.write_text(nt, encoding='utf-8')
    print(f"{'converted' if apply else 'would convert'} {len(changed)} files; tokens used: "
          + json.dumps(dict(sorted(stats.items(), key=lambda x: -x[1]))))
    for c in changed: print('  ' + c)
    if any(c.endswith(ARTWORK) for c in changed):
        print('  note: drawings were recolored; run scripts/hv-artwork.py --apply to restore their real colors')

if __name__ == '__main__':
    main()
